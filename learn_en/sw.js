const CACHE_NAME = 'ogden-pwa-20260816-pronunciation-2';
const CORE_ASSETS = [
  '/',
  '/learn_en/index.html',
  '/learn_en/manifest.json',
  '/learn_en/favicon.png',
  '/learn_en/icons/ogden-icon-192.png',
  '/learn_en/icons/ogden-icon-512.png',
  '/learn_en/icons/ogden-maskable-512.png',
  '/learn_en/icons/ogden-apple-touch-icon.png'
];

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(CORE_ASSETS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(
        keys.filter(key => key !== CACHE_NAME).map(key => caches.delete(key))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);

  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/api/tts')) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then(response => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then(cache => cache.put('/learn_en/index.html', copy));
          return response;
        })
        .catch(() => caches.match('/learn_en/index.html'))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then(cached => {
      if (cached) return cached;
      return fetch(request).then(response => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE_NAME).then(cache => cache.put(request, copy));
        }
        return response;
      });
    })
  );
});
